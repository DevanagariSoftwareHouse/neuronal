function spec = questionnaire_spec()
%QUESTIONNAIRE_SPEC Original prompts and analytical scope for Q01-Q15.
spec=struct([]);
spec(1).id='q01';
spec(1).script='q01_firing_rate';
spec(1).question='Which brain area has the lowest firing rate over the entire recording?';
spec(1).method='Full-recording count divided by recording exposure for every mapped cluster, including silent clusters; arithmetic mean by area.';
spec(1).units='spikes/s/cluster';
spec(1).limitations='Cluster resampling conditions on this recording. Mapped clusters are not automatically validated single neurons.';
spec(1).labels={'Area 1';'Area 2';'Area 3'};
spec(2).id='q02';
spec(2).script='q02_broadband_power';
spec(2).question='Which brain area has the highest broadband LFP power (1-100 Hz) over the entire recording?';
spec(2).method='Welch power integrated from 1 to 100 Hz in nonoverlapping blocks; equal channel weighting within each block.';
spec(2).units='LFP units squared';
spec(2).limitations='Stationary resampling acts on ordered block-power summaries. Reference choice, omitted tail and channel validity affect the target.';
spec(2).labels={'Area 1';'Area 2';'Area 3'};
spec(3).id='q03';
spec(3).script='q03_ripple_density';
spec(3).question='Which brain area (if any) has the highest density of ripples (i.e. "hippocampal" ripples traditionally occurring during sharp wave-ripples)?';
spec(3).method='120-200 Hz envelope candidates: robust onset z=2, peak z=5, duration 25-150 ms; union across channels within 20 ms; counts per minute.';
spec(3).units='candidate events/min';
spec(3).limitations='These are candidate ripples. Sharp-wave morphology and artifacts require validation before hippocampal ripple identification.';
spec(3).labels={'Area 1';'Area 2';'Area 3'};
spec(4).id='q04';
spec(4).script='q04_spike_interactions';
spec(4).question='In which brain area are pairwise spike train interactions strongest at the 100 ms timescale?';
spec(4).method='100 ms spike counts; Pearson correlation for each nonconstant cluster pair; mean absolute correlation per time block.';
spec(4).units='absolute Pearson r';
spec(4).limitations='Shared neurons make pair estimates dependent. Resample block summaries; shared task drive is not synaptic interaction.';
spec(4).labels={'Area 1';'Area 2';'Area 3'};
spec(5).id='q05';
spec(5).script='q05_undirected_connectivity';
spec(5).question='Which brain area pair has the strongest undirected functional connectivity?';
spec(5).method='100 ms counts averaged over clusters in each area; absolute correlation between area populations in each time block.';
spec(5).units='absolute Pearson r';
spec(5).limitations='Compare the three connections with paired estimates. Shared input and unequal cluster counts can affect connectivity.';
spec(5).labels={'Area 1 <-> 2';'Area 1 <-> 3';'Area 2 <-> 3'};
spec(6).id='q06';
spec(6).script='q06_directed_connectivity';
spec(6).question='Which brain area pair has the strongest directed functional connectivity?';
spec(6).method='20 ms population counts; detrended, standardized conditional VAR with five lags; log reduced/full residual variance ratio per block.';
spec(6).units='log variance ratio';
spec(6).limitations='Exploratory in-sample predictability, not causal evidence. Check residuals, stationarity and lag choice; the target is mean blockwise predictability.';
spec(6).labels={'Area 1 -> 2';'Area 3 -> 2';'Area 3 -> 1'};
spec(7).id='q07';
spec(7).script='q07_fast_spiking';
spec(7).question='Which brain area has the highest density of putative fast-spiking interneurons based on spike waveform and/or spike train features?';
spec(7).method='Classify finite negative-trough/following-positive-peak waveforms using configured sample rate and trough-to-peak width threshold; fraction narrow by area.';
spec(7).units='fraction of classifiable clusters';
spec(7).limitations='Recorded-cluster proportion is not anatomical density or confirmed interneuron identity. Exclude invalid waveforms explicitly.';
spec(7).labels={'Area 1';'Area 2';'Area 3'};
spec(8).id='q08';
spec(8).script='q08_phase_locking';
spec(8).question='In which brain area are spikes most strongly phase-locked to its own LFP in the 4-10 Hz range?';
spec(8).method='4-10 Hz zero-phase filtered LFP on a prespecified channel; complex interpolation at spike times; discard two-second edges; PPC for eligible clusters.';
spec(8).units='PPC';
spec(8).limitations='Default minimum is 50 spikes per cluster. Cluster intervals condition on estimated PPC and eligibility; check reference-channel sensitivity.';
spec(8).labels={'Area 1';'Area 2';'Area 3'};
spec(9).id='q09';
spec(9).script='q09_excitation_inhibition';
spec(9).question='Which brain area has the highest excitation-inhibition ratio (i.e., the strongest relative excitation)?';
spec(9).method='Estimate the narrow-waveform fraction p and transform its interval to broad/narrow count ratio (1-p)/p, reversing endpoints.';
spec(9).units='broad/narrow ratio';
spec(9).limitations='Physiological excitation/inhibition cannot be identified from waveform counts. Boundary samples have no reported empirical ratio interval.';
spec(9).labels={'Area 1';'Area 2';'Area 3'};
spec(10).id='q10';
spec(10).script='q10_intrinsic_timescale';
spec(10).question='Which brain area has the shortest intrinsic neuronal timescale during baseline activity?';
spec(10).method='One-second pretrial baseline without trial overlap; across-trial correlations of 50 ms bins; fit A exp(-lag/tau)+C and summarize accepted tau estimates.';
spec(10).units='seconds';
spec(10).limitations='Requires at least 20 baseline trials, six finite lags, tau 25-1000 ms and R-squared at least 0.5. Interval conditions on accepted fits.';
spec(10).labels={'Area 1';'Area 2';'Area 3'};
spec(11).id='q11';
spec(11).script='q11_variable_a_information';
spec(11).question='Which brain area contains most information about variable A? Exclude inter-trial intervals. The specific trial segment on which to base the analysis is not given because it cannot be determined a priori for variable A.';
spec(11).method='Matched fixed cluster subsets; whole-trial mean firing rates; contiguous five-fold ridge decoding of A; mutual information of held-out confusion matrix.';
spec(11).units='bits';
spec(11).limitations='Joint trial resampling conditions on fitted predictions. This is decoded information, not full neural mutual information. Circular-shift nulls are separate.';
spec(11).labels={'Area 1';'Area 2';'Area 3'};
spec(12).id='q12';
spec(12).script='q12_variable_c_decoding';
spec(12).question='During which trial segment is variable C best decoded?';
spec(12).method='All clusters; mean rates in the three trial segments; common contiguous five-fold decoder splits; balanced accuracy with fixed classes.';
spec(12).units='balanced accuracy';
spec(12).limitations='Joint trial resampling preserves segment pairing. Full prediction coverage is required; absent-class replicates fail explicitly. Training uncertainty and duration effects remain separate.';
spec(12).labels={'Trial start to stimulus';'Stimulus to outcome';'Outcome to trial end'};
spec(13).id='q13';
spec(13).script='q13_dimensionality';
spec(13).question='In which brain area is the dimensionality of neural activity highest? Use the segments from stimulus presentation to outcome to answer this question.';
spec(13).method='Fixed matched cluster subset in each area; 100 ms bins within stimulus-to-outcome trials; covariance participation ratio tr(C)^2/tr(C^2), recomputed on whole resampled trials.';
spec(13).units='effective dimensions';
spec(13).limitations='Point and replicate estimators use the same subset. Longer trials contribute more bins; raw covariance weights high-variance units.';
spec(13).labels={'Area 1';'Area 2';'Area 3'};
spec(14).id='q14';
spec(14).script='q14_modularity';
spec(14).question='In which brain area is modularity the lowest? Use the entirety of the recording to answer this question.';
spec(14).method='Fixed matched cluster subset; positive Pearson spike-count network at 100 ms; weighted greedy modularity in each time block.';
spec(14).units='weighted modularity Q';
spec(14).limitations='Mean blockwise modularity is not one whole-session graph statistic. Negative edges are discarded; inspect node-count and resolution sensitivity.';
spec(14).labels={'Area 1';'Area 2';'Area 3'};
spec(15).id='q15';
spec(15).script='q15_signal_complexity';
spec(15).question='In which brain area is the neural signal most complex? Use the segments from stimulus presentation to trial end to answer this question.';
spec(15).method='Permutation entropy of order 3 with approximately 10 ms delay; linear detrending; exclude tied patterns; mean across channels per stimulus-to-end trial.';
spec(15).units='normalized entropy';
spec(15).limitations='High entropy may reflect noise. Assess trial length, valid pattern count, embedding parameters and spectral sensitivity.';
spec(15).labels={'Area 1';'Area 2';'Area 3'};
end
