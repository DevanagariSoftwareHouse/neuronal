function c = storage_capabilities(st)
%STORAGE_CAPABILITIES Explicit operational limits, independent of benchmarks.
st=storage_validate(st); b=st.backend;
if strcmp(b,'sqlite'), b='mat'; elseif strcmp(b,'hybrid'), b=st.array_backend; end
c=struct('backend',st.backend,'payload_backend',b, ...
    'catalog',any(strcmp(st.backend,{'sqlite','hybrid'})), ...
    'range_read',true,'partial_io',~strcmp(b,'mat') || strcmp(st.mat_version,'-v7.3'), ...
    'append',true,'streaming_append',false,'partial_write',false, ...
    'concurrent_write',false,'concurrent_read_write',false, ...
    'persistent_handles',false,'fsync',false,'writable',~st.readonly, ...
    'complex',strcmp(b,'mat'),'records',strcmp(b,'mat'));
% MAT partial I/O applies to dense numeric/logical arrays only.
end
