function st = storage_defaults(backend)
%STORAGE_DEFAULTS Canonical storage policy; no filesystem side effects.
% ST=storage_defaults('hdf5'|'binary'|'mat'|'sqlite'|'hybrid').
% Defaults preserve input class. SQLite indexes MAT payloads; hybrid indexes
% HDF5 (or binary) payloads. See matlab/STORAGE.md for the storage contract.
if nargin<1 || isempty(backend), backend='hdf5'; end
st=struct('backend',lower(char(backend)), ...
    'root',fullfile(pwd,'data','derived'), 'readonly',false, ...
    'overwrite',false, 'create_parents',true, 'precision','preserve', ...
    'chunk_samples',65536, 'compression',0, 'byte_order','ieee-le', ...
    'mat_version','-v7.3', 'mat_compression',false, ...
    'array_backend','hdf5', 'busy_timeout_ms',5000);
end
