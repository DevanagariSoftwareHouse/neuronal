#!/usr/bin/env python3
"""Keep matlab/path, the method-specification chapter, the arsenal proofs and
shared/theorems.yml consistent.

    python3 books/tools/arsenal_registry.py --check   # used by `make check`
    python3 books/tools/arsenal_registry.py --write   # regenerate the ARS block

Sources of truth:
  * matlab/path/*.m                                 -- the functions
  * electrophysiology/chapters/12_method_specifications.tex
        \\methodentry{<file>.m}{computes}{relies on: ARS ids}{review}
  * formal_foundations/chapters/10_arsenal/*.tex
        \\begin{theorem|proposition}[ARS-XXX-NNN --- title]
The ARS block of shared/theorems.yml is generated from these; hand-written
entries above the marker are preserved.
"""
from pathlib import Path
import re
import sys

BOOKS = Path(__file__).resolve().parent.parent
REPO = BOOKS.parent
MATLAB = REPO / "matlab" / "path"
SPEC = BOOKS / "electrophysiology" / "chapters" / "12_method_specifications.tex"
PROOFS = sorted((BOOKS / "formal_foundations" / "chapters" / "10_arsenal").glob("*.tex"))
REGISTRY = BOOKS / "shared" / "theorems.yml"
MARKER = "  # --- generated by books/tools/arsenal_registry.py: do not edit below ---"

ID = re.compile(r"ARS-[A-Z]+-\d{3}")
THEOREM = re.compile(r"\\begin\{(?:theorem|proposition)\}\[(ARS-[A-Z]+-\d{3})\s+---\s+([^\]]+)\]")
ENTRY = re.compile(r"\\methodentry\{([A-Za-z0-9_]+)\.m\}\s*\n\{.*?\}\s*\n\{(.*?)\}\s*\n\{", re.S)


def functions():
    return sorted(p.stem for p in MATLAB.glob("*.m"))


def theorems():
    found = {}
    for path in PROOFS:
        for ident, title in THEOREM.findall(path.read_text(encoding="utf-8")):
            if ident in found:
                raise SystemExit(f"duplicate theorem id {ident}")
            found[ident] = (title.strip(), path.relative_to(REPO).as_posix())
    return found


def entries():
    text = SPEC.read_text(encoding="utf-8")
    result = {}
    for name, relies in ENTRY.findall(text):
        if name in result:
            raise SystemExit(f"duplicate method entry {name}")
        result[name] = sorted(set(ID.findall(relies)))
    return result


def generated_block(thms, ents):
    users = {k: [] for k in thms}
    for name, ids in ents.items():
        for ident in ids:
            users.setdefault(ident, []).append(name)
    spec = SPEC.relative_to(REPO).as_posix()
    lines = [MARKER]
    for ident in sorted(thms):
        title, path = thms[ident]
        title = title.replace('"', "'")
        lines += [
            f"  - id: {ident}",
            f"    name: \"{title}\"",
            f"    exposition: {path}",
            f"    analysis: {spec}",
            "    lean: null",
            f"    status: {'cited' if '(cited)' in title else 'proved-in-text'}",
            "    matlab:",
        ]
        lines += [f"      - matlab/path/{n}.m" for n in sorted(users.get(ident, []))] or ["      []"]
    definitional = sorted(n for n, ids in ents.items() if not ids)
    lines.append("definitional_methods:")
    lines += [f"  - matlab/path/{n}.m" for n in definitional]
    return "\n".join(lines) + "\n"


def compose(thms, ents):
    current = REGISTRY.read_text(encoding="utf-8")
    head = current.split(MARKER)[0].rstrip("\n") + "\n"
    return head + generated_block(thms, ents)


def check(thms, ents):
    problems = []
    funcs = set(functions())
    specified = set(ents)
    for name in sorted(funcs - specified):
        problems.append(f"matlab/path/{name}.m has no \\methodentry in {SPEC.name}")
    for name in sorted(specified - funcs):
        problems.append(f"{SPEC.name} specifies {name}.m, which is not in matlab/path")
    for name, ids in sorted(ents.items()):
        for ident in ids:
            if ident not in thms:
                problems.append(f"{name}.m relies on {ident}, which no arsenal chapter states")
    cited = {i for ids in ents.values() for i in ids}
    for ident in sorted(set(thms) - cited):
        problems.append(f"{ident} is stated but no method relies on it")
    if REGISTRY.read_text(encoding="utf-8") != compose(thms, ents):
        problems.append("shared/theorems.yml is stale: run books/tools/arsenal_registry.py --write")
    return problems


def main(argv):
    thms, ents = theorems(), entries()
    if "--write" in argv:
        REGISTRY.write_text(compose(thms, ents), encoding="utf-8")
        print(f"Wrote {len(thms)} ARS theorems and {len(ents)} methods to {REGISTRY.relative_to(REPO)}")
        return 0
    problems = check(thms, ents)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print(f"Arsenal registry consistent: {len(ents)} methods, {len(thms)} ARS theorems.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
